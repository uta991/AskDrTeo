const PREFIX: Record<MilestoneDomain, string> = {
  GROSS_MOTOR: 'GM',
  FINE_MOTOR: 'FM',
  SOCIAL_EMOTIONAL: 'SE',
  COGNITIVE_LANGUAGE: 'CL',
};

async function main() {
  const counters = new Map<string, number>();

  for (const [ageMonths, domain, questionKa, redFlag] of ROWS) {
    const key = `${PREFIX[domain]}_${String(ageMonths).padStart(2, '0')}`;
    const index = (counters.get(key) ?? 0) + 1;
    counters.set(key, index);

    const code = `${key}_${String(index).padStart(2, '0')}`;

    await prisma.milestoneQuestion.upsert({
      where: { code },
      create: { code, ageMonths, domain, questionKa, redFlag: redFlag ?? false, sortOrder: index },
      update: { ageMonths, domain, questionKa, redFlag: redFlag ?? false, sortOrder: index },
    });
  }

  const total = await prisma.milestoneQuestion.count({ where: { deletedAt: null } });
  console.log(`✓ ${ROWS.length} კითხვა ჩაიწერა, ბაზაში სულ ${total}`);
}

main().finally(() => prisma.$disconnect());
