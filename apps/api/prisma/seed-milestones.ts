const PREFIX: Record<MilestoneDomain, string> = {
  GROSS_MOTOR: 'GM',
  FINE_MOTOR: 'FM',
  SOCIAL_EMOTIONAL: 'SE',
  COGNITIVE_LANGUAGE: 'CL',
};

async function main() {
  // ძველი ცნობარი მთლიანად ქრება — შევსებული კითხვარებიც, რადგან
  // ისინი წაშლილ კითხვებზე მიუთითებდნენ და შედეგი აზრს კარგავდა
  await prisma.milestoneAnswerEntry.deleteMany();
  await prisma.milestoneAssessment.deleteMany();
  const removed = await prisma.milestoneQuestion.deleteMany();
  console.log(`ძველი ცნობარი გასუფთავდა: ${removed.count} კითხვა`);

  const counters = new Map<string, number>();

  for (const [ageMonths, domain, questionKa, redFlag] of ROWS) {
    const key = `${PREFIX[domain]}_${String(ageMonths).padStart(2, '0')}`;
    const index = (counters.get(key) ?? 0) + 1;
    counters.set(key, index);

    await prisma.milestoneQuestion.create({
      data: {
        code: `${key}_${String(index).padStart(2, '0')}`,
        ageMonths,
        domain,
        questionKa,
        redFlag: redFlag ?? false,
        sortOrder: index,
      },
    });
  }

  console.log(`✓ ახალი ცნობარი: ${ROWS.length} კითხვა, ` +
    `${new Set(ROWS.map((r) => r[0])).size} ასაკობრივ ეტაპზე`);
}

main().finally(() => prisma.$disconnect());
