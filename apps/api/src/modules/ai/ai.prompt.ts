/** ბავშვის კონტექსტი — ასაკის გარეშე პასუხი თითქმის ყოველთვის ცდება. */
export function childContext(child: {
  firstName: string;
  ageMonths: number;
  isPreterm: boolean;
  gestationalWeek: number | null;
}): string {
  const age =
    child.ageMonths < 24
      ? `${child.ageMonths} თვის`
      : `${Math.floor(child.ageMonths / 12)} წლის`;

  const preterm =
    child.isPreterm && child.gestationalWeek
      ? ` ნაადრევად დაიბადა, ორსულობის ${child.gestationalWeek} კვირაზე.`
      : '';

  return `მშობელი ${child.firstName}-ზე გეკითხება. ბავშვი ${age}-ია.${preterm}`;
}
